-- Table and column names follow the brief literally (camelCase), hence the quoted identifiers.
-- Money columns use NUMERIC(15, 2): exact decimal storage with cent precision.
CREATE TABLE "timeDeposits" (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "planType" VARCHAR(50)    NOT NULL,
    days       INTEGER        NOT NULL,
    balance    NUMERIC(15, 2) NOT NULL
);

CREATE TABLE withdrawals (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timeDepositId" INTEGER        NOT NULL REFERENCES "timeDeposits" (id),
    amount          NUMERIC(15, 2) NOT NULL,
    date            DATE           NOT NULL
);

CREATE INDEX "withdrawals_timeDepositId_idx" ON withdrawals ("timeDepositId");
